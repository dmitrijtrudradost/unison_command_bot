"""Доменные исключения ядра Team Bot.

Исключения отделяют ожидаемые ошибки пользователя от технических сбоев
адаптеров. Оркестратор преобразует их в русские тексты из ``core.messages``.
"""


class DomainError(Exception):
    """Базовый класс ожидаемой ошибки бизнес-правила."""


class ValidationError(DomainError):
    """Сообщает о неверных или неполных аргументах команды."""


class PermissionDenied(DomainError):
    """Сообщает о недостаточной роли для операции."""


class NotFoundError(DomainError):
    """Сообщает, что сущность не найдена в области команды."""


class IdentityRequired(DomainError):
    """Сообщает, что внешний аккаунт ещё не зарегистрирован."""


class TeamRequired(DomainError):
    """Сообщает, что текущий чат не привязан к доступной команде."""


class AccessCodeError(DomainError):
    """Сообщает, что одноразовый код неверен, истёк или использован."""
