"""Хеширование одноразовых кодов доступа.

Хеш считается в адаптере хранения, чтобы ядро работало с открытым кодом только
в момент выдачи пользователю. Повторный показ из БД невозможен.
"""

import hashlib


def hash_access_code(code: str) -> str:
    """Возвращает SHA-256 хеш одноразового кода.

    Аргументы:
        code: открытое значение, показанное пользователю один раз.

    Возвращает:
        Шестнадцатеричный дайджест фиксированной длины.
    """
    digest = hashlib.sha256()
    digest.update(b"teambot.access_code.v1\0")
    digest.update(code.encode("utf-8"))
    return digest.hexdigest()
